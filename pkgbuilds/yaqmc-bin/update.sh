#!/usr/bin/env bash
# Build & install the latest YAQMC release as a pacman package (yaqmc-bin).
#
# 背景：AUR 的 yaqmc-bin 维护滞后（长期停在 0.1.1），这里直接取上游 GitHub
# Release 的官方 .deb，按 AUR 原包的布局重新打包成 pacman 包再安装。
#
# 用法：
#   ./update.sh                # 取最新 release
#   ./update.sh 0.1.2          # 指定版本
#   ./update.sh 0.1.2 --no-install
#   ./update.sh --check        # 只输出上游最新版本号（供 pacman.nu update 调用）
#
# 可调环境变量：
#   GH_MIRROR=https://ghfast.top/   # 下载镜像（为空则直连）
#   YAQMC_DEB=/path/to.deb          # 用本地 deb，跳过下载
set -euo pipefail
HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
WORKDIR=${XDG_CACHE_HOME:-$HOME/.cache}/yaqmc-pkgbuild
mkdir -p "$WORKDIR"
cd "$WORKDIR"

REPO=YAQMC/YAQMC
MIRROR=${GH_MIRROR-https://ghfast.top/}
NO_INSTALL=0
CHECK=0
VER=""
for arg in "$@"; do
  case "$arg" in
    --no-install) NO_INSTALL=1 ;;
    --check) CHECK=1 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) VER=$arg ;;
  esac
done

# ---- 1. 版本 ----
if [[ -z $VER ]]; then
  VER=$(curl -fsSL --max-time 30 "https://api.github.com/repos/$REPO/releases/latest" \
        | sed -n 's/.*"tag_name": *"v\?\([^"]*\)".*/\1/p' | head -1)
fi
[[ -n $VER ]] || { echo "无法确定版本号，请显式传入，例如 ./update.sh 0.1.2" >&2; exit 1; }
if (( CHECK )); then echo "$VER"; exit 0; fi
echo "==> 目标版本: $VER"

# ---- 2. 下载 ----
fetch() { # <url> <out>
  local url=$1 out=$2
  if [[ -n $MIRROR ]] && curl -fsSL --retry 2 --max-time 600 -o "$out" "$MIRROR$url"; then
    return 0
  fi
  echo "    镜像失败，改为直连" >&2
  curl -fsSL --retry 2 --max-time 600 -o "$out" "$url"
}

if [[ -n ${YAQMC_DEB-} ]]; then
  cp -- "$YAQMC_DEB" YAQMC-linux-x64.deb
  echo "    使用本地 deb: $YAQMC_DEB"
else
  echo "==> 下载 .deb"
  fetch "https://github.com/$REPO/releases/download/v$VER/YAQMC-linux-x64.deb" YAQMC-linux-x64.deb
fi
echo "==> 下载 LICENSE"
fetch "https://raw.githubusercontent.com/$REPO/v$VER/LICENSE" LICENSE

DEB_SHA=$(sha256sum YAQMC-linux-x64.deb | awk '{print $1}')
LIC_SHA=$(sha256sum LICENSE | awk '{print $1}')
echo "    deb     sha256: $DEB_SHA"
echo "    LICENSE sha256: $LIC_SHA"

# ---- 3. 生成 PKGBUILD（沿用 AUR 原包布局，仅版本/校验和不同）----
cat > PKGBUILD <<EOF
# Generated by pkgbuilds/yaqmc-bin/update.sh — do not edit by hand.
# Based on AUR yaqmc-bin (maintainer: Osilvfe <osilvfe@gmail.com>).
pkgname=yaqmc-bin
pkgver=$VER
pkgrel=1
pkgdesc='Unofficial QQ Music client (official Electron binary release)'
arch=('x86_64')
url='https://github.com/$REPO'
license=('GPL-3.0-or-later')
depends=(
  'alsa-lib' 'at-spi2-core' 'cairo' 'dbus' 'expat' 'glib2' 'gtk3'
  'hicolor-icon-theme' 'libcups' 'libnotify' 'libsecret' 'libx11' 'libxcb'
  'libxcomposite' 'libxdamage' 'libxext' 'libxfixes' 'libxkbcommon'
  'libxrandr' 'libxss' 'libxtst' 'mesa' 'nspr' 'nss' 'pango' 'systemd-libs'
  'xdg-utils'
)
optdepends=('libayatana-appindicator: system tray support')
provides=('yaqmc')
conflicts=('yaqmc' 'yaqmc-git')
options=('!strip' '!debug')
source=("LICENSE::file://$PWD/LICENSE")
source_x86_64=("YAQMC-linux-x64.deb::file://$PWD/YAQMC-linux-x64.deb")
sha256sums=('$LIC_SHA')
sha256sums_x86_64=('$DEB_SHA')

prepare() {
  install -d "\${srcdir}/deb" "\${srcdir}/pkg"
  bsdtar -xf "\${srcdir}/YAQMC-linux-x64.deb" -C "\${srcdir}/deb"
  bsdtar -xf "\${srcdir}/deb/data.tar.xz" -C "\${srcdir}/pkg"
}

package() {
  install -d "\${pkgdir}/opt/yaqmc"
  cp -a "\${srcdir}/pkg/opt/YAQMC/." "\${pkgdir}/opt/yaqmc/"

  install -d "\${pkgdir}/usr/bin"
  ln -s /opt/yaqmc/yaqmc "\${pkgdir}/usr/bin/yaqmc"

  install -Dm644 "\${srcdir}/LICENSE" "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"

  install -Dm644 "\${srcdir}/pkg/usr/share/applications/org.yaqmc.desktop" \\
    "\${pkgdir}/usr/share/applications/org.yaqmc.desktop"
  sed -i 's|^Exec=.*|Exec=/opt/yaqmc/yaqmc %U|' \\
    "\${pkgdir}/usr/share/applications/org.yaqmc.desktop"

  install -d "\${pkgdir}/usr/share/icons"
  cp -a "\${srcdir}/pkg/usr/share/icons/hicolor/." "\${pkgdir}/usr/share/icons/hicolor/"

  # Arch 默认允许非特权 user namespace，不随包提供 setuid 的 chrome-sandbox
  chmod 0755 "\${pkgdir}/opt/yaqmc/chrome-sandbox"
}
EOF
echo "==> 已生成 PKGBUILD (pkgver=$VER)"

# ---- 4. 构建 ----
rm -rf src pkg
makepkg -f --noconfirm

PKG=$(ls -1t yaqmc-bin-"$VER"-1-x86_64.pkg.tar.zst 2>/dev/null | head -1)
[[ -n $PKG ]] || { echo "构建产物未找到" >&2; exit 1; }
echo "==> 构建完成: $PKG"

# ---- 5. 安装 ----
if (( NO_INSTALL )); then
  echo "==> 跳过安装（--no-install），安装包保留在: $PWD/$PKG"
  exit 0
fi
sudo pacman -U --noconfirm "$PKG"

# ---- 6. 清理（保留 PKGBUILD/脚本，省空间）----
rm -rf src pkg YAQMC-linux-x64.deb LICENSE "$PKG"
echo "==> 完成（构建目录: $WORKDIR）。重开 YAQMC 以使用新版本。"
